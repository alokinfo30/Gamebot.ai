export function getLocalizedCommentary(rawText: string, langCode: string = 'en'): string {
  if (!rawText) return '';
  const code = (langCode as LanguageCode) || 'en';
  if (code === 'en') return rawText;

  const dict = COMMENTARY_DICTIONARY[code] || COMMENTARY_DICTIONARY['en'];
  const enDict = COMMENTARY_DICTIONARY['en'];

  for (const key in enDict) {
    if (rawText.trim() === enDict[key] && dict[key]) {
      return dict[key];
    }
  }

  return rawText;
}

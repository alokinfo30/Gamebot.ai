/**
 * Detect user's preferred language automatically based on browser locale or localStorage
 */
export function detectUserLanguage(): LanguageCode {
  if (typeof window === 'undefined') return 'en';

  try {
    const saved = localStorage.getItem('ludo_preferred_language') as LanguageCode;
    if (saved && TRANSLATIONS[saved]) {
      return saved;
    }

    const browserLang = (navigator.language || (navigator as unknown as { userLanguage?: string }).userLanguage || 'en').toLowerCase();

    // Check exact or prefix matches
    for (const lang of SUPPORTED_LANGUAGES) {
      if (browserLang.startsWith(lang.code)) {
        return lang.code;
      }
    }
  } catch (e) {
    console.error('Failed to detect browser language', e);
  }

  return 'en';
}

/**
 * Get translation string for current language code
 */
export function t(key: string, langCode: string = 'en'): string {
  const code = (langCode as LanguageCode) || 'en';
  const dict = TRANSLATIONS[code] || TRANSLATIONS['en'];
  return dict[key] || TRANSLATIONS['en'][key] || key;
}

/**
 * Get speech synthesis language tag (e.g. 'hi-IN', 'es-ES', 'en-US')
 */
export function getSpeechLang(langCode: string = 'en'): string {
  const found = SUPPORTED_LANGUAGES.find((l) => l.code === langCode);
  return found ? found.speechLang : 'en-US';
}

